#!/usr/bin/env node
/**
 * ci/generate-tier-doc.mjs — plan item 7.4.
 *
 * `docs/retier-benchmark-results.md` was hand-maintained with no generator, and
 * it was one of FOUR descriptions of which model each role ships on. RC7's
 * measurement: corrected rows rotted within 26 hours. A document that must be
 * kept in step by hand with a fact stored elsewhere is an invariant with no
 * writer — this release's §2, applied to documentation.
 *
 * So the shipped-tier table is DERIVED from `agents/*.md` frontmatter, which is
 * the only place a tier actually takes effect. It cannot disagree with the build
 * because it is read from the build.
 *
 * The same run syncs each `evals/<role>/spec.json`'s `current` arm to the shipped
 * model. A spec whose `current` arm is not what ships measures a retier that did
 * not happen, and re-running it produces a number about a configuration no agent
 * runs.
 *
 *   node ci/generate-tier-doc.mjs           # write
 *   node ci/generate-tier-doc.mjs --check   # exit 1 if anything is stale
 */

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'fs';
import { join, dirname, resolve } from 'path';
import { fileURLToPath } from 'url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const AGENTS = join(REPO, 'agents');
const EVALS = join(REPO, 'evals');
const DOC = join(REPO, 'docs', 'retier-benchmark-results.md');

const check = process.argv.includes('--check');

/** role -> model, read from the frontmatter that actually takes effect. */
function shippedModels() {
  const out = new Map();
  for (const f of readdirSync(AGENTS).filter((f) => /^evor-.*\.md$/.test(f))) {
    const m = readFileSync(join(AGENTS, f), 'utf8').match(/^model:\s*(\S+)\s*$/m);
    if (m) out.set(f.replace(/\.md$/, ''), m[1]);
  }
  return new Map([...out].sort());
}

function renderDoc(models) {
  const rows = [...models].map(([role, model]) =>
    `| \`${role.replace(/^evor-/, '')}\` | ${model} | \`agents/${role}.md\` |`).join('\n');

  return `# Shipped model tiers

<!-- GENERATED BY ci/generate-tier-doc.mjs — DO NOT EDIT BY HAND. -->
<!-- Run \`node ci/generate-tier-doc.mjs\` after changing any agent's frontmatter. -->

This table is **derived from \`agents/*.md\` frontmatter**, which is the only place
a tier takes effect. It cannot disagree with the build, because it is read from
the build.

It replaces the hand-maintained \`retier-benchmark-results.md\` (plan item 7.4).
That file was one of four descriptions of which model each role ships on, had no
generator, and RC7 measured corrected rows rotting within 26 hours. A document
kept in step by hand with a fact stored elsewhere is an invariant with no writer.

## Where the branch ends up

| role | now | source of truth |
|---|---|---|
${rows}

## On the benchmark numbers that used to live here

They are **not reproduced, and they are not retracted.** RC7's finding is that
they were *right about a narrower thing than they were quoted for*: the tier
evals ran with **no MCP tools attached**, so they measured judgement quality on a
prompt, and were then cited for a claim about role capability in a system where
every role's job is to call tools.

Phase 7 fixed the instrument — \`ci/role-eval.mjs\` passes \`--mcp-config\`, the
harness refuses to score a role-eval where a mandated tool was never called, and
each run records whether tools were attached.

**Item 8.1 has now re-measured every role through it**: 9 specs, both arms per
spec, 5 repeats, 930 calls, 0 harness errors. Three of nine clear the 10pp
non-inferiority margin. **Two SHIPPED retiers do not** — \`evor-sage\` and
\`evor-mutagen\`, both on haiku. See §3 of \`docs/v1-cost-and-verification.md\`
for the per-role table and \`docs/evidence/matrix-81.json\` for the underlying
calls.

This page still states only what ships, which is a fact about the frontmatter.
It is not the evidence page, and a tier appearing here has never meant the tier
is justified — 8.1 is why that distinction matters.
`;
}

const models = shippedModels();
const doc = renderDoc(models);

let stale = [];

if (!existsSync(DOC) || readFileSync(DOC, 'utf8') !== doc) {
  stale.push('docs/retier-benchmark-results.md');
  if (!check) writeFileSync(DOC, doc);
}

// Sync each spec's `current` arm to the shipped model.
for (const dir of readdirSync(EVALS)) {
  const specPath = join(EVALS, dir, 'spec.json');
  if (!existsSync(specPath)) continue;
  const spec = JSON.parse(readFileSync(specPath, 'utf8'));
  const shipped = models.get(spec.role);
  if (!shipped) continue;
  const arms = spec.arms ?? [];
  const current = arms.find((a) => /current/i.test(a.label ?? ''));
  if (!current) continue;

  const changes = [];
  if (current.model !== shipped) {
    changes.push(`current ${current.model} -> ${shipped}`);
    if (!check) current.model = shipped;
  }

  // The matrix must MEASURE something. Syncing `current` to the shipped tier can
  // collide with the comparison arm — three forge reviewers ship opus and their
  // pre-retier arm was also opus, so both arms became identical and the eval
  // would have compared a model with itself while reporting a comparison.
  const other = arms.find((a) => a !== current);
  if (other && other.model === shipped) {
    const alternative = shipped === 'opus' ? 'sonnet' : shipped === 'sonnet' ? 'haiku' : 'sonnet';
    changes.push(`comparison arm ${other.model} -> ${alternative} (was identical to current)`);
    if (!check) {
      other.model = alternative;
      other.label = `${alternative} (candidate)`;
    }
  }

  if (!changes.length) continue;
  stale.push(`evals/${dir}/spec.json (${changes.join('; ')})`);
  if (!check) writeFileSync(specPath, JSON.stringify(spec, null, 2) + '\n');
}

if (check && stale.length) {
  process.stderr.write(
    'Stale, regenerate with `node ci/generate-tier-doc.mjs`:\n  ' + stale.join('\n  ') + '\n'
  );
  process.exit(1);
}
process.stdout.write(
  (check ? 'up to date' : stale.length ? `regenerated:\n  ${stale.join('\n  ')}` : 'no change') + '\n'
);
