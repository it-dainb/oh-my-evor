/**
 * ci/bench-freeze.mjs — one freeze manifest for evor-eval-bench.
 *
 *   node ci/bench-freeze.mjs --group tool --author A [--unconfirmed]
 *   node ci/bench-freeze.mjs --check
 *
 * WHY THIS IS CENTRAL AND NOT PER-AUTHOR.
 *
 * Four authors produced three incompatible freeze mechanisms:
 *   - evidence/FREEZE-C.json  hash map under `scenarios`, manifest-relative paths
 *   - lifecycle/FREEZE.json   count under `scenarios`, hash map under `files`, repo-relative
 *   - tool/                   a git commit reference in prose — which pinned NOTHING:
 *                             that commit contains zero bench files and none are tracked
 *
 * A runner reading one convention verifies nothing for the other authors and
 * reports success. That is the bench's own subject — a stated integrity property
 * with no writer behind it — occurring in the bench's plumbing, which is why the
 * mechanism is owned in one place instead of negotiated between four agents.
 *
 * Trap 6.7: pairs are frozen BEFORE any live run, so that no scenario can be
 * fitted to a model's answer. A manifest that cannot detect an edit does not
 * deliver that, however authoritative it reads.
 */
import { createHash } from 'crypto';
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'fs';
import { join, relative, resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const BENCH = join(REPO, 'evals', 'bench');
const MANIFEST = join(BENCH, 'FREEZE.json');
const arg = (n, d) => { const i = process.argv.indexOf(`--${n}`); return i > -1 ? process.argv[i + 1] : d; };
const has = (n) => process.argv.includes(`--${n}`);
const sha = (p) => createHash('sha256').update(readFileSync(p)).digest('hex');

function walk(dir, out = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    // `.omc/` IS OPERATIONAL STATE THE HARNESS WRITES, NOT CORPUS.
    //
    // Running the bench caused an OMC hook to write
    // `.omc/state/sessions/<id>/pre-tool-advisory-throttle.json` INTO a frozen
    // fixture in the repo. The freeze correctly reported UNFROZEN — the bench
    // was mutating its own corpus by being run. Excluding it here keeps the
    // manifest about authored content; the write itself is recorded as a defect
    // (plan item 2.18) because a fixture that changes when you look at it is not
    // a fixture.
    // `.omc/` is harness state; `__pycache__/` is bytecode a postcondition run
    // leaves behind. Neither is authored corpus, and both appeared inside frozen
    // fixtures purely by being executed.
    if (e.isDirectory()) { if (e.name !== '.omc' && e.name !== '__pycache__') walk(p, out); }
    // The manifest cannot hash itself, and a per-author manifest is superseded.
    else if (!/FREEZE.*\.json$/.test(e.name)) out.push(p);
  }
  return out;
}

const load = () => (existsSync(MANIFEST) ? JSON.parse(readFileSync(MANIFEST, 'utf8')) : { $comment: [], groups: {} });

if (has('check')) {
  const m = load();
  let bad = 0, n = 0;

  // A GROUP THAT IS NOT IN THE MANIFEST IS NOT VERIFIED BY IT. `evals/bench/mcp/`
  // appeared with the stub servers and the check reported "all match" while an
  // entire directory sat outside its view — the freeze inspecting only what it
  // already knew about, which is exactly what cannot detect new files.
  for (const d of readdirSync(BENCH, { withFileTypes: true })) {
    if (!d.isDirectory() || d.name in (m.groups ?? {})) continue;
    console.log(`UNFROZEN-GROUP  evals/bench/${d.name}/ (${walk(join(BENCH, d.name)).length} files) — freeze it or exclude it deliberately`);
    bad++;
  }
  for (const [group, g] of Object.entries(m.groups ?? {})) {
    for (const [rel, want] of Object.entries(g.files ?? {})) {
      const p = join(REPO, rel);
      n++;
      if (!existsSync(p)) { console.log(`MISSING   ${rel}`); bad++; continue; }
      if (sha(p) !== want) { console.log(`DRIFT     ${rel}`); bad++; }
    }
    const live = walk(join(BENCH, group)).map((p) => relative(REPO, p));
    for (const rel of live) if (!(rel in (g.files ?? {}))) { console.log(`UNFROZEN  ${rel}`); bad++; }
  }
  console.log(bad ? `\n${bad} problem(s) across ${n} frozen file(s)` : `bench freeze: ${n} files, all match`);
  process.exit(bad ? 1 : 0);
}

const group = arg('group');
if (!group || !existsSync(join(BENCH, group))) { console.error(`--group <dir> required; no evals/bench/${group}`); process.exit(2); }
const m = load();
const files = {};
for (const p of walk(join(BENCH, group)).sort()) files[relative(REPO, p)] = sha(p);
m.$comment = [
  'GENERATED BY ci/bench-freeze.mjs — DO NOT EDIT BY HAND.',
  'Trap 6.7: scenarios are frozen before any live run, so none can be fitted to a',
  'model answer. Any edit after a scored run must be logged in the author note,',
  're-frozen here, and that scenario re-run from zero.',
];
m.groups = m.groups ?? {};
m.groups[group] = {
  author: arg('author', '?'),
  frozen_at: arg('at', new Date(statSync(join(BENCH, group)).mtimeMs).toISOString()),
  // An author who did not confirm finality is recorded as such rather than
  // silently presented as having signed off.
  finality_confirmed_by_author: !has('unconfirmed'),
  count: Object.keys(files).length,
  files,
};
writeFileSync(MANIFEST, JSON.stringify(m, null, 1) + '\n');
console.log(`froze ${group} (author ${m.groups[group].author}): ${Object.keys(files).length} files${has('unconfirmed') ? ' — AUTHOR DID NOT CONFIRM FINALITY' : ''}`);
