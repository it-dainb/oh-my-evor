#!/usr/bin/env node
/**
 * ci/generate-provenance.mjs — plan item A-04 / P-01.
 *
 * Writes `.claude-plugin/MANIFEST.sha256`: the commit the tree was built from,
 * plus a sha256 for every shipped file.
 *
 * WHY PER-FILE HASHES AND NOT JUST A VERSION. During the field run, 17 files in
 * the installed tree were modified in place — including `hooks/stop.mjs`, part
 * of the enforcement layer — and 26 `.bak-*` files were left beside them. The
 * version string in `plugin.json` did not change, because a version string does
 * not change when files are patched underneath it. Lane A and lane P had to
 * establish the drift by hand, with `diff -rq` against a fresh clone, after the
 * fact. A version identifies a release; only hashes identify a TREE.
 *
 *   node ci/generate-provenance.mjs           # write
 *   node ci/generate-provenance.mjs --check   # exit 1 if stale
 */

import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'fs';
import { join, relative, dirname, resolve, sep } from 'path';
import { execFileSync } from 'child_process';
import { createHash } from 'crypto';
import { fileURLToPath } from 'url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(REPO, '.claude-plugin', 'MANIFEST.sha256');
const check = process.argv.includes('--check');

/**
 * The shipped tree is the TRACKED tree.
 *
 * A hand-maintained skip list was written first and immediately swept in 6053
 * files from gitignored `refs/` and `logs/`. `git ls-files` is the authority
 * because it is the same set the release contains — the list is read from the
 * build rather than maintained beside it, which is 7.4's lesson applied here.
 *
 * An INSTALLED tree has no `.git`, so generation requires a checkout; verifying
 * an installed tree uses the file list the manifest itself carries, which is the
 * only list available there and the only one that matters.
 */
function trackedFiles() {
  const out = execFileSync('git', ['ls-files', '-z'], { cwd: REPO, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  return out.split('\0').filter(Boolean).filter((f) => !f.endsWith('MANIFEST.sha256')).sort();
}

function commit() {
  try {
    return execFileSync('git', ['rev-parse', 'HEAD'], { cwd: REPO, encoding: 'utf8' }).trim();
  } catch {
    return null;
  }
}

const files = trackedFiles();
const hashes = {};
for (const f of files) {
  const abs = join(REPO, f);
  if (!existsSync(abs)) continue;   // tracked but deleted in the working tree
  hashes[f] = createHash('sha256').update(readFileSync(abs)).digest('hex');
}

const version = JSON.parse(readFileSync(join(REPO, '.claude-plugin', 'plugin.json'), 'utf8')).version ?? null;
const manifest = {
  $comment: [
    'GENERATED BY ci/generate-provenance.mjs — DO NOT EDIT BY HAND.',
    'Binds the shipped tree to the commit it was built from, per file.',
    'A version string does not change when files are patched in place; 17 were,',
    'including hooks/stop.mjs, and nothing reported it for 19 hours (A-04 / P-01).',
    'Verify an installed tree with: evor doctor  (see _check_plugin_tree_drift).',
  ],
  version,
  commit: commit(),
  generated_at: new Date().toISOString(),
  file_count: Object.keys(hashes).length,
  files: hashes,
};

const rendered = JSON.stringify(manifest, null, 2) + '\n';

if (check) {
  if (!existsSync(OUT)) { process.stderr.write('MANIFEST.sha256 is missing\n'); process.exit(1); }
  const prior = JSON.parse(readFileSync(OUT, 'utf8'));
  const drift = [];
  for (const [f, h] of Object.entries(hashes)) {
    if (prior.files?.[f] !== h) drift.push(prior.files?.[f] ? `modified: ${f}` : `added: ${f}`);
  }
  for (const f of Object.keys(prior.files ?? {})) if (!(f in hashes)) drift.push(`removed: ${f}`);
  if (drift.length) {
    process.stderr.write(`tree differs from MANIFEST.sha256:\n  ${drift.slice(0, 20).join('\n  ')}\n`);
    process.exit(1);
  }
  process.stdout.write(`up to date (${Object.keys(hashes).length} files)\n`);
} else {
  writeFileSync(OUT, rendered);
  process.stdout.write(`wrote ${relative(REPO, OUT)}: ${Object.keys(hashes).length} files @ ${manifest.commit?.slice(0, 7) ?? 'no-git'}\n`);
}
